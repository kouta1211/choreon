/** コマが自分に付ける目印。帯はこれを見て「コマの上か」を判じる */
export const SCENE_CARD_ATTRIBUTE = "data-scene-id";

/**
 * 押した所が【コマの上】か。
 *
 * ■ なぜ帯が知る必要があるか
 * コマは押した時点で伝播を止めない（2026-08-22 の決めごと。止めると
 * **コマの上から波形を引けなくなる** — コマの帯は帯全体の大半を占める）。
 * そのぶん、コマの上のタップは**帯にも届く**。
 *
 * 帯は「動かさずに離したらその位置へシーク」する。シークは
 * `sceneIndexAtSeconds` で【その時刻を過ぎた最後のシーン】を選ぶ。
 * **コマは時刻の真上に中心を置いている**ので、コマの左半分を押すと
 * そのシーンの時刻より手前になり、**1つ前のシーンが選ばれる**。
 * コマ自身の選択を、帯が上書きしていた（実機の報告・2026-08-24）。
 *
 * ■ 引くのは止めない
 * 見ているのは【離したときにシークするか】だけ。押したまま横へ引く
 * 操作は今までどおり帯が受ける。
 *
 * 旗と束ねは押した時点で伝播を止めるので、ここまで来ない。
 */
export function startedOnSceneCard(target: EventTarget | null): boolean {
  return (
    target instanceof Element &&
    target.closest(`[${SCENE_CARD_ATTRIBUTE}]`) !== null
  );
}
