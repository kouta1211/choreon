/**
 * 「客席を上にする」設定のための、上下の鏡。
 *
 * ■ 保存されている座標は動かさない
 * 反転は【描き方】の話で、作品の中身ではない。座標を書き換えると、
 * 既定の向きで開いた人と食い違い、共有した図が別の隊形になる。
 * そこで「保存する向き(ステージ座標)」と「画面に描く向き」を分け、
 * 描く直前に toScreenY で写す。
 *
 * ■ CSSで面ごと鏡にする手は採れない
 * 入れ物に scaleY(-1) を掛ける方が短いが、それをやるとダンサーを掴んだ
 * ときに指と本体が逆へ動く。打ち消そうとしても、dnd-kit は掴んでいる
 * 要素の位置ずれを毎フレーム測って補正するため、こちらの打ち消しと
 * 引っ張り合って座標が発散する(実測: 指を40px動かすと本体が
 * 反対側の端まで飛ぶ)。だから【座標の側】を写す。
 *
 * 写すのは次の4つ。どれも画面に出す直前・受け取った直後に1回だけ:
 *   1. 立ち位置・導線・バミリの Y (toScreenY)
 *   2. 指の動き(px)→ ステージ座標 の Y の符号 (stageYSign)
 *   3. 向き(度) (mirrorAngle)
 *   4. 「客席側 / バックステージ」の札(Stage.tsx)
 */

/**
 * ステージ座標のYを、画面に描くYへ写す。
 *
 * 反転していなければ何もしない。反転中は上下を入れ替える。
 * 1マスの格子は上下対称なので、整数の立ち位置は写しても整数のまま
 * (＝格子への吸着は画面側で数えたままで正しい)。
 */
export function toScreenY(
  y: number,
  heightUnits: number,
  isAudienceOnTop: boolean,
): number {
  return isAudienceOnTop ? heightUnits - y : y;
}

/** 画面のYとステージのYの向き。反転中は逆 */
export function stageYSign(isAudienceOnTop: boolean): 1 | -1 {
  return isAudienceOnTop ? -1 : 1;
}

/**
 * 上下の鏡に映した向き(度)。0度=客席側という規約は変えない。
 *
 * 角度の規約は「0度が画面の下、時計回りに増える」。上下だけを鏡にすると、
 * 下向き(0度)は上向き(180度)になり、左右の成分はそのまま残る。
 * これは 180 - angle にあたる。
 */
export function mirrorAngle(angle: number): number {
  return (((180 - angle) % 360) + 360) % 360;
}
