/**
 * いま、シーンを増やしてよいか。
 *
 * ■ 曲を入れている作品では、**鳴らしている最中だけ**（2026-08-22 に user が決定）
 * 曲を入れた時点で、その人は**曲ありきで隊形を考えている**。止まった
 * ままで増やすと、置かれるのは「なんとなくの秒数」になり、あとから
 * 音に合わせ直す作業が生まれる。時刻を直す手段は時間軸でコマをつまむ
 * 操作しか無いので、その手直しは重い。
 *
 * 鳴らしている間なら、押した瞬間が**そのまま意図**になる。
 * だから「増やせない」のではなく、**増やし方が1つに決まる**。
 *
 * ■ 曲が無ければ今までどおり
 * 合わせる相手が居ないので、押した所に基準が無い。
 * いま見ているシーンの次へ入れる（`duplicateTimeSeconds`）。
 *
 * ■ 最初の1つも同じ
 * 「はじまり」だから0秒でよい、という考え方もあるが、**曲を入れた作品で
 * イントロが長い**なら、振付が始まるのは0秒ではない。ここだけ例外に
 * すると「最初だけ止まっていても押せる」を覚える必要ができる。
 */
export function canAddScene({
  hasMusic,
  isPlaying,
}: {
  hasMusic: boolean;
  isPlaying: boolean;
}): boolean {
  return !hasMusic || isPlaying;
}
