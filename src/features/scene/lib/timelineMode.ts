/**
 * 時間軸を出すか、順番だけにするか。
 *
 * ■ なぜ切り替えるのか（実機の要望 2026-08-19）
 * シーンは「曲の何秒目か」を持っていて、下の帯もその位置に並べている。
 * **合わせる相手が居ないのに時刻だけがある**と、
 *
 *  - 時刻が近いシーンのコマが帯の上で重なる
 *  - 「27.3秒目」という数字が、振付として何の意味も持たない
 *
 * ということが起きる。合わせる相手が1つも無いときは、時刻を見せるのを
 * やめて【順番】と【何秒で動くか】だけにする。
 *
 * ■ 合わせる相手が「無い」とは
 * **曲もメトロノームも無いとき**（user の判断 2026-08-19）。
 *
 * メトロノームのスイッチだけで決めないのは、**曲を入れたままスイッチを
 * 切っている**作品があるため。そこで時刻を隠すと、曲に合わせて置いた隊形を
 * 曲に合わせて直せなくなる。
 *
 * 逆に曲が無くてもメトロノームが鳴っているなら、拍という物差しがある
 * （シーンの変わり目を拍に合わせたい）ので、時刻は要る。
 *
 * ■ 保存しているものは変えない
 * `scenes.time_seconds` はそのまま持ち続ける。順番も移動時間もそこから
 * 出せるので、**画面が何を見せて何を編集させるか**だけを変える。
 * 列を消すと、曲を入れた瞬間に時刻を作り直すことになり、
 * 「曲を入れたら隊形が散った」という壊れ方をする。
 */

export function isOrderOnlyTimeline({
  hasMusic,
  isMetronomeEnabled,
}: {
  hasMusic: boolean;
  isMetronomeEnabled: boolean;
}): boolean {
  return !hasMusic && !isMetronomeEnabled;
}
